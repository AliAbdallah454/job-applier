"""The list of skills. This file is only data, so it is the one place to edit.

To add a skill, add its name to a category and run `npm run types` in frontend/. To add a category,
add a Category: the enum, the model, the API and the web app all follow from it. A category's key
is stored in profiles, so do not change it once it is in use.

A name must be in one category only. To rename or remove a skill, change it here and, for a rename,
add the old name to OTHER_NAMES: saved profiles still hold it, and it is replaced when they are
read. A removed skill moves to the profile's additional information.
"""

from typing import NamedTuple


class Category(NamedTuple):
    key: str
    label: str
    skills: tuple[str, ...]


def aws(*services):
    """AWS services are always "AWS <service>"; saved "Amazon X" and "X" spellings map to them."""
    return tuple(f"AWS {service}" for service in services)


